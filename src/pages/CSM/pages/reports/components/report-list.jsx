import { useMemo } from 'react';
import { Check, Loader, X } from 'lucide-react';
import { Badge } from '@/components/ui/badge';
import { DataGridColumnHeader } from '@/components/ui/data-grid-column-header';
import {
  DataGridTableRowSelect,
  DataGridTableRowSelectAll,
} from '@/components/ui/data-grid-table';
import { Skeleton } from '@/components/ui/skeleton';
import { DateFormatter } from '@/components/custom/date-formatter';
import Table from '@/components/custom/table';
import { useAuth } from '@/auth/context/auth-context';
import useReportStore from '../store';
import CsmReportDropdown from './dropdowns/report-list-dropdown';
import { Profile } from '@/components/custom/profile';

const enum_map = {
  revalidation: 'Full Revalidation Report',
  fullrevalidation: 'Organization Level Revalidation Report',
  vulnerability: 'Vulnerability Report',
  'cspm-internal-assessment-vuln': 'Vulnerability Report',
  'cspm-internal-assessment-vuln report': 'Vulnerability Report',
  'cspm internal assessment vuln report': 'Vulnerability Report',
  fullexec: 'Full Executive Report',
  executive: 'Executive Report',
  asset: 'Asset Report',
  allvulns: 'Organization Wide Vulnerabilities Report',
  'allvulns-assessment': 'Assessment Level Vulnerabilities Report',
  certificate: 'Certificate of Completion',
  sla: 'SLA Report',
  compliance: 'Compliance Report',
};

const getReportDisplayName = (row) => {
  if (row.type === 'allvulns' && row.assessmentId) {
    return 'Assessment Level Vulnerabilities Report';
  }
  if (row.type && enum_map[row.type]) {
    return enum_map[row.type];
  }
  if (row.name && enum_map[row.name]) {
    return enum_map[row.name];
  }
  if (row.type?.includes('vuln') || row.name?.includes('vuln')) {
    return 'Vulnerability Report';
  }
  if (row.type?.includes('exec') || row.name?.includes('exec')) {
    return 'Executive Report';
  }
  if (row.type?.includes('revalidation') || row.name?.includes('revalidation')) {
    return 'Revalidation Report';
  }
  if (row.type?.includes('asset') || row.name?.includes('asset')) {
    return 'Asset Report';
  }
  return row.name || row.title || 'Report';
};

function getColumns(user) {
  return [
    // {
    //   id: 'select',
    //   accessorKey: '_id',
    //   header: ({ table }) => <DataGridTableRowSelectAll table={table} />,
    //   cell: ({ row }) => <DataGridTableRowSelect row={row} />,
    //   enableSorting: false,
    //   enableHiding: false,
    //   size: 10,
    //   meta: { skeleton: <Skeleton className="h-7 w-[20px]" /> },
    // },
    {
      id: 'name',
      accessorFn: (row) => getReportDisplayName(row),
      header: ({ column }) => <DataGridColumnHeader title="Report Name" column={column} />,
      cell: ({ row }) => (
        <div className="flex flex-col">
          <span className="text-sm font-medium text-mono truncate">
            {getReportDisplayName(row.original)}
          </span>
        </div>
      ),
      enableSorting: false,
      size: 260,
      meta: { skeleton: <Skeleton className="h-7" /> },
    },

    {
      id: 'generatedBy',
      accessorFn: (row) => row.generatedBy?.name,
      header: ({ column }) => <DataGridColumnHeader title="Generated By" column={column} />,
      cell: ({ row }) => {
        const user = row.original.generatedBy;
        if (!user) return <span className="text-sm text-muted-foreground">—</span>;
        return (
          <Profile
            name={user.name}
            email={user.email}
            userId={user._id || user.id}
            size="28px"
            showName
          />
        );
      },
      enableSorting: false,
      size: 180,
      meta: { skeleton: <Skeleton className="h-7" /> },
    },
    {
      id: 'assessment',
      accessorFn: (row) => row.assessment?.title,
      header: ({ column }) => <DataGridColumnHeader title="Assessment" column={column} />,
      cell: ({ row }) => (
        <div>{row.original.assessment?.title || '—'}</div>
      ),
      enableSorting: false,
      size: 160,
      meta: { skeleton: <Skeleton className="h-7" /> },
    },
    {
      id: 'state',
      accessorFn: (row) => row.status,
      header: ({ column }) => <DataGridColumnHeader title="State" column={column} />,
      cell: ({ row }) => {
        const status = row.original.status;
        const createdAt = row.original.createdAt;
        const isOld = createdAt
          ? Date.now() - new Date(createdAt).getTime() > 3600000
          : false;

        let displayStatus = status;
        let badgeVariant =
          status === 'completed'
            ? 'success'
            : status === 'failed'
              ? 'destructive'
              : 'warning';

        if (!status === 'completed' && isOld) {
          displayStatus = 'failed';
          badgeVariant = 'destructive';
        }

        return (
          <Badge size="lg" variant={badgeVariant} appearance="outline">
            {status === 'completed' ? (
              <Check />
            ) : status === 'failed' ? (
              <X />
            ) : (
              <Loader className="animate-spin" />
            )}
            {displayStatus.charAt(0).toUpperCase() + displayStatus.slice(1)}
          </Badge>
        );
      },
      enableSorting: false,
      size: 110,
      meta: { skeleton: <Skeleton className="h-7" /> },
    },
    {
      id: 'createdAt',
      accessorFn: (row) => row.createdAt,
      header: ({ column }) => <DataGridColumnHeader title="Created" column={column} />,
      cell: ({ row }) => (
        <span className="text-sm text-muted-foreground">
          <DateFormatter date={row.original.createdAt} />
        </span>
      ),
      enableSorting: false,
      size: 140,
      meta: { skeleton: <Skeleton className="h-7" /> },
    },
    ...(user?.role === 'Auditor'
      ? []
      : [
        {
          id: 'actions',
          header: ({ column }) => <DataGridColumnHeader title="" column={column} />,
          cell: ({ row }) => <CsmReportDropdown row={row} />,
          enableSorting: false,
          size: 70,
                meta: { skeleton: <Skeleton className="h-7" /> },

        },
      ]),
  ];
}

const CsmReportList = ({ data = [], paginationData, isLoading, isFetching }) => {
  const pagination = useReportStore((s) => s.pagination);
  const setPagination = useReportStore((s) => s.setPagination);
  const searchQuery = useReportStore((s) => s.searchQuery);
  const setSearchQuery = useReportStore((s) => s.setSearchQuery);
  const rowSelection = useReportStore((s) => s.rowSelection);
  const setRowSelection = useReportStore((s) => s.setRowSelection);
  const { user } = useAuth();

  const columns = useMemo(() => getColumns(user), [user]);

  return (
    <Table
      data={data}
      columns={columns}
      isLoading={isLoading || isFetching}
      pagination={pagination}
      setPagination={setPagination}
      totalPages={paginationData?.totalPages}
      totalCount={paginationData?.total}
      search={searchQuery}
      setSearch={setSearchQuery}
      rowSelection={rowSelection}
      setRowSelection={setRowSelection}
      enableSorting={false}
      searchPlaceholder="Search reports..."
      searchWidth="60"
    />
  );
};

export default CsmReportList;
