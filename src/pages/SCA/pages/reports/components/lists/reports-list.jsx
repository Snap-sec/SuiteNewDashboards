import React, { useMemo } from 'react';
import { MoreHorizontal, Download, Check, X, Loader } from 'lucide-react';
import { toast } from 'sonner';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { DataGridColumnHeader } from '@/components/ui/data-grid-column-header';
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from '@/components/ui/dropdown-menu';
import { Skeleton } from '@/components/ui/skeleton';
import { ButtonWithConfirm } from '@/components/custom/button-with-confirmation';
import { DateFormatter } from '@/components/custom/date-formatter';
import { Profile } from '@/components/custom/profile';
import Table from '@/components/custom/table';
import { useDeleteScaReportMutation } from '@/services/sca/reportsApi';
import appConfig from '@/config/appConfig';
import useStore from '../../store';
import TableToolbarFilters from '@/components/common/table-toolbar-filters';
import { useAuth } from '@/auth/context/auth-context';

const ActionsCell = ({ row }) => {
  const [deleteScaReport, { isLoading: isDeleting }] = useDeleteScaReportMutation();

  const isPendingProcessing = row.original.status === 'pending' || row.original.status === 'processing';
  const isFailed = row.original.status === 'failed';

  const downloadReport = () => {
    if (row.original.type === 'executive' || row.original.format === 'PDF') {
      window.open(`/sca-reports/executive?reportId=${row.original.reportId}`, '_blank');
    } else {
      const downloadReportURL = `${appConfig.BASE_URL}/sca/api/v1/reports/${row.original._id}/download/`;
      window.location.href = downloadReportURL;
    }
  };

  const handleDeleteReport = () => {
    toast.promise(deleteScaReport(row.original.reportId).unwrap(), {
      loading: 'Deleting Report...',
      success: 'Report Deleted Successfully',
      error: 'Failed to delete report',
    });
  };

  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button variant="ghost" className="h-8 w-8 p-0">
          <MoreHorizontal className="h-4 w-4" />
          <span className="sr-only">Open menu</span>
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end" className="w-[160px]">
        <DropdownMenuItem
          onClick={downloadReport}
          disabled={isPendingProcessing || isFailed}
          className="cursor-pointer gap-2"
        >
          Download
        </DropdownMenuItem>

        <DropdownMenuSeparator />

        <ButtonWithConfirm
          confirm={true}
          confirmOnInput={row.original.name}
          variant="ghost"
          disabled={isDeleting}
          onConfirm={handleDeleteReport}
          className="w-full justify-start text-destructive px-2 py-1.5 h-auto font-normal text-sm rounded-md hover:!bg-red-300/20 hover:text-destructive text-left"
          dialog={
            <div className="flex flex-col items-center gap-2">
              <p className="text-center font-semibold">
                Are you sure you want to delete this report?
              </p>
              <p className="text-sm text-muted-foreground text-center">
                This action cannot be undone.
              </p>
            </div>
          }
        >
          Delete
        </ButtonWithConfirm>
      </DropdownMenuContent>
    </DropdownMenu>
  );
};

function getColumns(isAuditor = false) {
  return [
    {
      id: 'name',
      accessorFn: (row) => row.name,
      header: ({ column }) => (
        <DataGridColumnHeader title="Report Name" column={column} />
      ),
      cell: ({ row }) => (
        <div className="flex flex-col">
          <span className="font-medium">
            {row.original.name}
          </span>

        </div>
      ),
      enableSorting: false,
      size: 300,
      meta: {
        skeleton: <Skeleton className="h-7" />,
      },
    },
    {
      id: 'owner',
      accessorFn: (row) => row.createdBy?.name,
      header: ({ column }) => (
        <DataGridColumnHeader title="Generated By" column={column} />
      ),
      cell: ({ row }) => (
        <Profile
          name={row?.original?.createdBy?.name || 'Admin User'}
          email={row?.original?.createdBy?.email || 'admin@snapsec.co'}
          role={row?.original?.createdBy?.role || 'Administrator'}
        />
      ),
      enableSorting: false,
      size: 220,
      meta: {
        skeleton: <Skeleton className="h-7" />,
      },
    },
    {
      id: 'state',
      accessorFn: (row) => row.status,
      header: ({ column }) => (
        <DataGridColumnHeader title="Status" column={column} />
      ),
      cell: ({ row }) => {
        const createdAt = row?.original?.createdAt;
        const status = row.original.status;

        // Check if createdAt is more than 1 hour (3600000 ms) ago
        const isOld = createdAt
          ? Date.now() - new Date(createdAt).getTime() > 3600000
          : false;

        let displayStatus = status || 'completed';
        let badgeVariant =
          status === 'completed'
            ? 'success'
            : status === 'failed'
              ? 'destructive'
              : 'warning';

        // If older than 1 hour, override to 'failed'
        if (status !== 'completed' && isOld) {
          displayStatus = 'failed';
          badgeVariant = 'destructive';
        }

        return (
          <div className="flex items-center gap-1.5">
            <Badge size="lg" variant={badgeVariant} appearance="outline">
              {displayStatus === 'completed' ? (
                <Check />
              ) : displayStatus === 'failed' ? (
                <X />
              ) : (
                <Loader className="animate-spin" />
              )}
              {displayStatus.charAt(0).toUpperCase() + displayStatus.slice(1)}
            </Badge>
          </div>
        );
      },
      enableSorting: false,
      size: 110,
      meta: {
        skeleton: <Skeleton className="h-7" />,
      },
    },
    {
      id: 'date',
      accessorFn: (row) => row.createdAt,
      header: ({ column }) => (
        <DataGridColumnHeader title="Created At" column={column} />
      ),
      cell: ({ row }) => (
        <DateFormatter date={row.original.createdAt} />
      ),
      enableSorting: false,
      size: 140,
      meta: {
        skeleton: <Skeleton className="h-7" />,
      },
    },
    ...(!isAuditor
      ? [
          {
            id: 'actions',
            header: () => '',
            cell: ({ row }) => <ActionsCell row={row} />,
            enableSorting: false,
            size: 50,
            meta: {
              skeleton: <Skeleton className="h-7" />,
            },
          },
        ]
      : []),
  ];
}


const ReportList = ({ data = [], isLoading, isFetching, totalCount, totalPages }) => {
  const { user } = useAuth();
  const isAuditor = user?.role === 'Auditor';

  const pagination = useStore((state) => state.pagination);
  const setPagination = useStore((state) => state.setPagination);
  const search = useStore((state) => state.searchQuery);
  const setSearch = useStore((state) => state.setSearchQuery);
  const filters = useStore((state) => state.filters);
  const setFilters = useStore((state) => state.setFilters);
  const rowSelection = useStore((state) => state.rowSelection);
  const setRowSelection = useStore((state) => state.setRowSelection);

  const columns = useMemo(() => getColumns(isAuditor), [isAuditor]);

  return (
    <Table
      data={data?.data}
      columns={columns}
      isLoading={isLoading || isFetching}
      pagination={pagination}
      setPagination={setPagination}
      totalCount={totalCount}
      totalPages={totalPages}
      manualPagination={true}
      search={search}
      setSearch={setSearch}
      toolbar={
        <TableToolbarFilters
          supportedFilters={data?.advanced_filters}
          filters={filters}
          setFilters={setFilters}
        />
      }
      rowSelection={rowSelection}
      setRowSelection={setRowSelection}
      enableSorting={false}
      enableSearch={true}
      showPagination={true}
    />
  );
};

export default ReportList;
