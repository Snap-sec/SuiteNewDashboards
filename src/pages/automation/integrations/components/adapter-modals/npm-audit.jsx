function NpmAudit() {
  const { showInstallModal, setShowInstallModal } = useStore();
  const [search, setSearch] = useState('');

  // Get all assessments with search
  const { data: assessments, isLoading, isFetching } = useGetVmAssessmentsQuery({ search });

  const assessmentOptions = assessments?.data?.assessments?.map?.(assessment => ({
    value: assessment._id,
    label: assessment.name || assessment.title,
    id: assessment._id,
  })) || [];

  const form = useForm({
    resolver: zodResolver(npmAuditSchema),
    mode: "onChange",
    defaultValues: {
      name: '',
      assessmentId: '',
      adapterName: 'npm-audit',
    },
  });

  const [isDocsOpen, setIsDocsOpen] = useState(false);
  const [isInstallOpen, setIsInstallOpen] = useState(false);

  const [installNpmAudit] = useInstallVmAdapterMutation();

  useEffect(() => {
    let { type, slug } = showInstallModal;

    if (type === 'adapter' && slug === 'npm-audit') {
      setIsDocsOpen(true);
      setIsInstallOpen(false);
    } else if (type === 'npm-audit') {
      setIsInstallOpen(true);
      setIsDocsOpen(false);
      form.reset({
        name: '',
        assessmentId: '',
        adapterName: 'npm-audit',
      });
    } else {
      setIsDocsOpen(false);
      setIsInstallOpen(false);
    }
  }, [showInstallModal, form]);

  const handleInstallClose = () => {
    setIsInstallOpen(false);
    setShowInstallModal({});
    form.reset();
  };

  const handleInstall = (data) => {
    const finalPayload = {
      adapterName: 'npm-audit',
      name: data.name,
      assessmentId: data.assessmentId,
    };

    toast.promise(installNpmAudit(finalPayload).unwrap(), {
      loading: 'Installing npm audit Integration...',
      success: () => {
        handleInstallClose();
        return 'npm audit Integration has been installed';
      },
      error: 'Failed to install npm audit Integration',
    });
  };

  return (
    <>
      {/* Docs Modal */}
      <Modal
        open={isDocsOpen}
        setOpen={(val) => {
          setIsDocsOpen(val);
          if (!val) setShowInstallModal({});
        }}
        title="Guide for npm audit"
        description="Import Vulnerabilities from npm audit into VM"
        className="w-3/4"
      >
        <div className="h-[80vh] overflow-y-scroll">
          <Editor
            className="w-full"
            readOnly={true}
            defaultValue={npmAuditApiDocs}
          />
        </div>
      </Modal>

      {/* Install Modal */}
      <Modal
        open={isInstallOpen}
        setOpen={handleInstallClose}
        title="Integrate npm audit"
        description="Fetch vulnerabilities directly from npm audit scans"
        footer={
          <Button 
            variant="outline" 
            onClick={form.handleSubmit(handleInstall)} 
            disabled={form.formState.isSubmitting || !form.formState.isValid}
          >
            <Terminal /> Integrate
          </Button>
        }
      >
        <Form {...form}>
          <div className="flex flex-col gap-4">
            <FormField
              control={form.control}
              name="name"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Integration Name <span className="text-destructive">*</span></FormLabel>
                  <FormControl>
                    <InputWrapper className={form.formState.errors.name ? 'border-destructive' : ''}>
                      <Button size="sm" variant="dim" mode="icon" className="size-5 -ms-0.5" type="button">
                        <LayoutGrid />
                      </Button>
                      <Input placeholder="Enter integration name (e.g. npm-audit Prod)" {...field} />
                    </InputWrapper>
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />

            <FormField
              control={form.control}
              name="assessmentId"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Select Assessment <span className="text-destructive">*</span></FormLabel>
                  <FormControl>
                    <AssessmentSelect
                      value={field.value}
                      onChange={(option) => field.onChange(option.value)}
                      error={!!form.formState.errors.assessmentId}
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />
          </div>
        </Form>
      </Modal>
    </>
  );
}

export default NpmAudit;

