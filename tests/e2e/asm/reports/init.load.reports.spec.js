import { expect, test } from '@playwright/test';

test('initial load and interaction on ASM reports page', async ({ page }) => {
  // 1. Start on Home workspace (/) using auth storageState
  await page.goto('/');
  await page.waitForLoadState('domcontentloaded');

  // 2. Navigate to ASM Reports page
  await page.goto('/casm/reports');
  await page.waitForURL('**/casm/reports**');
  await page.waitForLoadState('domcontentloaded');

  // 3. Handle Empty State if no reports exist
  const emptyScreen = page.getByText('No Reports Found');
  if (await emptyScreen.isVisible()) {
    await expect(
      page.getByText('To get started, generate a new report on an assessment'),
    ).toBeVisible();
    return;
  }

  const main = page.getByRole('main');

  // 4. Verify Page Heading and Description
  const heading = main.getByRole('heading', { name: 'Reports', exact: true });
  await expect(heading).toBeVisible({ timeout: 15000 });
  await expect(main.getByText('List of Reports')).toBeVisible();

  // 5. Verify Supported Report Cards (Executive, Exposure, Attack Surface)
  await expect(main.getByText('Executive Report', { exact: true })).toBeVisible();
  await expect(main.getByText('Exposure Report', { exact: true })).toBeVisible();
  await expect(main.getByText('Attack Surface Report', { exact: true })).toBeVisible();

  // 6. Verify Report History Section and Table Headers
  await expect(main.getByText('Report History')).toBeVisible();

  const table = main.locator('table');
  if (await table.isVisible()) {
    const thead = table.locator('thead');
    await expect(thead.getByText('Name')).toBeVisible();
    await expect(thead.getByText('Generated By')).toBeVisible();
    await expect(thead.getByText('Status')).toBeVisible();
    await expect(thead.getByText('Created At')).toBeVisible();
  }

  // 7. Test Search input and clear functionality
  const searchInput = main
    .getByPlaceholder(/Search/i)
    .or(main.getByRole('textbox', { name: /Search/i }))
    .first();

  if (await searchInput.isVisible()) {
    await searchInput.fill('attack');
    await expect(searchInput).toHaveValue('attack');

    const clearBtn = main.locator('button:has(svg.lucide-x)').first();
    if (await clearBtn.isVisible()) {
      await clearBtn.click();
      await expect(searchInput).toHaveValue('');
    } else {
      await searchInput.fill('');
      await expect(searchInput).toHaveValue('');
    }
  }

  // 8. Test Pagination navigation if multiple pages exist
  const page2Btn = main.getByRole('button', { name: '2', exact: true });
  if (await page2Btn.isVisible()) {
    await page2Btn.click();
    const page1Btn = main.getByRole('button', { name: '1', exact: true });
    await expect(page1Btn).toBeVisible();
    await page1Btn.click();
  }
});