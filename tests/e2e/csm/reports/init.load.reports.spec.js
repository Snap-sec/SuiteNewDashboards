import { expect, test } from '@playwright/test';

test('initial load and interaction on CSM reports page', async ({ page }) => {
  // 1. Start on Home workspace (/) using auth storageState
  await page.goto('/');
  await page.waitForLoadState('domcontentloaded');

  // 2. Navigate to CSM Reports page (/csp-m/reports)
  await page.goto('/csp-m/reports');
  await page.waitForURL('**/csp-m/reports**');
  await page.waitForLoadState('domcontentloaded');

  const main = page.getByRole('main').or(page.locator('.p-4'));

  // 3. Handle Empty Screen or Page Heading
  const emptyScreen = main.getByText(/No Reports Found|No data available/i);
  const heading = main.getByRole('heading', {
    name: 'Reports',
    exact: true,
  });

  await expect(heading.or(emptyScreen)).toBeVisible({ timeout: 15000 });

  if (await emptyScreen.isVisible()) {
    await expect(
      page.getByText('No cloud compliance reports have been generated yet.'),
    ).toBeVisible();
    return;
  }

  // 4. Verify Page Heading & Description
  await expect(heading).toBeVisible();
  await expect(
    main.getByText(
      /View, generate, and manage cloud security and compliance reports|View and manage cloud compliance reports/i,
    ),
  ).toBeVisible();

  // 5. Verify Action Button (Generate Report)
  const generateReportBtn = main.getByRole('button', {
    name: /Generate Report/i,
  });
  if (await generateReportBtn.isVisible()) {
    await expect(generateReportBtn).toBeVisible();
  }

  // 6. Verify Table and Column Headers
  const table = main.locator('table');
  if (await table.isVisible()) {
    const thead = table.locator('thead');
    await expect(thead.getByText('Report Name')).toBeVisible();
    await expect(thead.getByText('Generated By')).toBeVisible();
    await expect(thead.getByText('Assessment')).toBeVisible();
    await expect(thead.getByText('State')).toBeVisible();
    await expect(thead.getByText('Created')).toBeVisible();
  }

  // 7. Test Search Input Interaction & Debounce
  const searchInput = main
    .getByPlaceholder('Search reports...')
    .or(main.getByPlaceholder(/Search/i))
    .or(main.getByRole('textbox', { name: /Search/i }))
    .first();
  if (await searchInput.isVisible()) {
    await searchInput.fill('audit');
    await expect(searchInput).toHaveValue('audit');
    await page.waitForTimeout(600); // Wait for debounce

    // Clear search
    const clearSearchBtn = main.locator('button:has(svg.lucide-x)').first();
    if (await clearSearchBtn.isVisible()) {
      await clearSearchBtn.click();
      await expect(searchInput).toHaveValue('');
    } else {
      await searchInput.fill('');
      await expect(searchInput).toHaveValue('');
    }
    await page.waitForTimeout(600);
  }

  // 8. Test Pagination if multiple pages exist
  const page2Btn = main.getByRole('button', { name: '2', exact: true });
  if ((await page2Btn.isVisible()) && (await page2Btn.isEnabled())) {
    await page2Btn.click();
    await page.waitForTimeout(500);

    const page1Btn = main.getByRole('button', { name: '1', exact: true });
    if ((await page1Btn.isVisible()) && (await page1Btn.isEnabled())) {
      await page1Btn.click();
      await page.waitForTimeout(500);
    }
  }
});